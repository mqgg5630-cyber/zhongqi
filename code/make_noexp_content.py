# 生成结果里不允许再出现的字眼（实验相关；"实验"两个字本身还允许出现在
# 文献结论与"区分计算预测与实验证据"这类说法里）
FORBIDDEN = ["抑菌", "纸片扩散", "肉汤稀释", "指示菌", "最低抑菌浓度",
             "阳性对照", "阴性对照", "人工合成", "活性验证",
             "大肠杆菌", "金黄色葡萄球菌"]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="生成去掉抑菌实验的送审版内容 md")
    ap.add_argument("--in", dest="src", default=str(SRC))
    ap.add_argument("--out", dest="dst", default=str(DST))
    args = ap.parse_args(argv)
    src, dst = Path(args.src), Path(args.dst)
    if not src.exists():
        print(f"[ERROR] 找不到原稿 {src}", file=sys.stderr)
        return 1

    text = src.read_text(encoding="utf-8")
    lines = text.splitlines()
    problems: list[str] = []

    # 1) 逐行删除：每一行都要能逐字对上
    drop_set: list[str] = []
    for s in DROP:
        if lines.count(s) != 1:
            problems.append(f"待删的行找不到或出现 {lines.count(s)} 次：{s[:40]}…")
        else:
            drop_set.append(s)
    # 2) 句中替换：每一句都要能逐字对上，且只出现一次
    for old, new in REPL:
        if text.count(old) != 1:
            problems.append(f"待替换的句子出现 {text.count(old)} 次：{old[:40]}…")
    if problems:
        print(f"[ABORT] 有 {len(problems)} 处对不上，未写任何文件：", file=sys.stderr)
        for p in problems:
            print(f"  - {p}", file=sys.stderr)
        return 1

    kept = [ln for ln in lines if ln not in drop_set]
    out = "\n".join(kept) + "\n"
    for old, new in REPL:
        out = out.replace(old, new, 1)

    # 3) 生成结果复核：实验相关字眼一个都不该剩
    left = [(i + 1, w, ln) for i, ln in enumerate(out.splitlines())
            for w in FORBIDDEN if w in ln]
    if left:
        print(f"[ABORT] 生成结果里还有 {len(left)} 处实验相关字眼：", file=sys.stderr)
        for n, w, ln in left:
            print(f"  line {n} [{w}] {ln[:60]}…", file=sys.stderr)
        return 1

    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(out, encoding="utf-8")

    seg = {k: 0 for k in "1234"}
    cur = None
    for ln in out.splitlines():
        if ln.startswith("## ") and ln[3:4] in seg:
            cur = ln[3:4]
            continue
        if ln.startswith("# ") or not ln.strip():
            if ln.startswith("# ") and not ln.startswith("## "):
                cur = None
            continue
        if cur:
            seg[cur] += 1
    print(f"saved -> {dst.relative_to(ROOT)}")
    print(f"  删除整行 {len(drop_set)} 行、句中替换 {len(REPL)} 处")
    print(f"  正文字段数：1={seg['1']} 2={seg['2']} 3={seg['3']} 4={seg['4']}"
          f"（含小标题行）")
    print("  实验相关字眼复核：0 处")
    print(f"接着跑：python code/build_ops.py --in {dst.relative_to(ROOT)} "
          f"--out build/ops_中期_无抑菌实验.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
