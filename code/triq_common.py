    ("力场（force field）", "定义原子间如何相互作用的公式与参数集合（键长、键角、二面角、静电、范德华）。常用：CHARMM36m、AMBER ff99SB-ILDN、a99SB-disp。"),
    ("水模型", "水分子怎么表示。TIP3P 最常用；TIP4P-D 专为无序蛋白设计；水模型会改变无序肽的尺寸（Rg）。"),
    ("系综（ensemble）", "模拟处在什么条件：NVT（恒温恒体积）、NPT（恒温恒压，最接近生理）。"),
    ("周期边界（PBC）", "把盒子重复拼起来消除边界效应；配合 PME 处理长程静电。"),
    ("自由能 ΔG", "判断能不能结合、能不能穿过膜的关键量。ΔG 越负越有利；1 kcal/mol 在 37 °C 下对应约 5.5 倍的平衡常数差异。"),
    ("PMF（平均力势）", "沿某条反应坐标（如距离 z）的自由能曲线；伞形采样与元动力学算的就是它。"),
